// --- the areas -----------------------------------------------------------------

/** What each area can score. Together they are the preliminary score. */
export const POSSIBLE_SCORE: Record<ScoreArea, number> = { outside: 25, inside: 25, unit: 50 };
export const PRELIMINARY_SCORE = POSSIBLE_SCORE.outside + POSSIBLE_SCORE.inside + POSSIBLE_SCORE.unit;

/** The three areas, in the order a report lists them. */
export const SCORE_AREAS: { area: ScoreArea; label: string; title: string }[] = [
  { area: 'outside', label: 'Outside', title: 'Outside Deficiencies' },
  { area: 'inside', label: 'Inside', title: 'Inside Deficiencies' },
  { area: 'unit', label: 'Units', title: 'Unit Deficiencies' },
];

/** Which of the three areas a value names; null when it names none of them. */
export function scoreArea(value: unknown): ScoreArea | null {
  const text = String(value ?? '').trim().toLowerCase();
  if (!text) return null;
  if (text.includes('outside') || text.includes('exterior') || text === 'site') return 'outside';
  if (text.includes('inside') || text.includes('interior') || text.includes('common')) return 'inside';
  if (text.includes('unit')) return 'unit';
  return null;
}

/** The area a finding was recorded in, wherever it keeps that. */
export function findingArea(finding: Loose | null | undefined): ScoreArea | null {
  if (!finding) return null;
  for (const value of [finding.area, finding._area, finding.inspectableArea, finding.subCategory, finding.category, finding.location]) {
    const area = scoreArea(value);
    if (area) return area;
  }
  return null;
}

export function scoreSeverity(value: unknown): ScoreSeverity {
  const text = String(value ?? '').trim().toLowerCase();
  if (text.includes('life') || text === 'critical') return 'Life-Threatening';
  if (text === 'severe' || text === 'major' || text === 'high') return 'Severe';
  if (text === 'low' || text === 'minor' || text === 'observation') return 'Low';
  return 'Moderate';
}

/** How severe a finding is, wherever it keeps that. */
export function findingSeverity(finding: Loose | null | undefined): ScoreSeverity {
  const inner: Loose = finding?.deficiency && typeof finding.deficiency === 'object' ? finding.deficiency : {};
  return scoreSeverity(finding?.severity ?? finding?.healthAndSafety ?? inner.severity ?? inner.healthAndSafety);
}

// --- reading a finding ---------------------------------------------------------

/**
 * What a finding says.
 *
 * The web saves a finding with its name and description at the top (title,
 * description, notes, unit). The app saves one with them inside
 * (deficiency.name, deficiency.detail, note, _unit). Everything that lists,
 * counts or scores findings reads them through here, so a deficiency recorded
 * on a phone is a deficiency on the website too. Read only at the top, a
 * finding from the app has no name and no description, and was taken for a
 * blank record and dropped.
 */
export interface FindingFacts {
  name: string;
  details: string;
  /** The inspector's note. */
  note: string;
  code: string;
  /** The building it was found in; '' when the finding names none. */
  building: string;
  /** The unit it was found in; '' for an outside or inside finding, or one that names none. */
  unit: string;
  area: ScoreArea | null;
  severity: ScoreSeverity;
  picture: string;
}

/** What stands where a place should be and names none. */
const NO_PLACE = /^(-|n\/?a|all[\s_-]*units?|unit multiple|multiple|property|building|unknown(-building)?|unspecified-unit|null|undefined)$/i;

const firstText = (...values: unknown[]): string => {
  for (const value of values) {
    const text = typeof value === 'string' ? value.trim() : typeof value === 'number' ? String(value) : '';
    if (text) return text;
  }
  return '';
};

/** The first of the values that names a real place: not blank, not "-", not "ALL_UNITS". */
const firstPlace = (...values: unknown[]): string => {
  for (const value of values) {
    const text = firstText(value);
    if (text && !NO_PLACE.test(text)) return text;
  }
  return '';
};

export function findingFacts(finding: Loose | null | undefined): FindingFacts {
  const row: Loose = finding || {};
  const inner: Loose = row.deficiency && typeof row.deficiency === 'object' ? row.deficiency : {};
  const area = findingArea(row);
  const photo = Array.isArray(row.photos) ? row.photos[0] : undefined;
  return {
    name: firstText(row.title, row.deficiencyName, row.selected, inner.name, inner.selected, row.name),
    details: firstText(row.description, row.details, row.detail, row.deficiencyDetails, inner.detail, inner.description),
    note: firstText(row.notes, row.note, row.comments),
    code: firstText(row.nspireCode, row.code, inner.code, inner.id),
    // An outside or inside finding has no unit: the web writes "-" there, and
    // the app writes the building again, as "_unit".
    building: firstPlace(
      row.building,
      row.buildingInspectionId,
      row.buildingId,
      row.buildingName,
      area === 'outside' || area === 'inside' ? row._unit : ''
    ),
    unit: area === 'outside' || area === 'inside'
      ? ''
      : firstPlace(row.unit, row.unitId, row.unitNumber, row._unit),
    area,
    severity: findingSeverity(row),
    picture: firstText(row.imageUri, row.imageUrl, typeof photo === 'string' ? photo : photo?.url, photo?.uri),
  };
}

/**
 * What makes two findings the same finding: where it was found and what it
 * says. '' for a record that says nothing -- a blank the database keeps from an
 * interrupted save -- which is not a finding at all.
 */
export function findingKey(finding: Loose | null | undefined): string {
  const facts = findingFacts(finding);
  if (!facts.name && !facts.details) return '';
  const row: Loose = finding || {};
  // A finding in none of the three areas is told apart by the place it does
  // name ("Kitchen", "Bath").
  const where = facts.area ?? firstText(row.area, row._area, row.subCategory, row.category);
  return [where, facts.building, facts.unit, facts.name, facts.details].join('|').toLowerCase();
}

// --- the sample size -----------------------------------------------------------

/**
 * How many of a property's units make up its sample, by how many units it
 * has: [from, to, sample]. It is the table lib/unitSamplingService picks the
 * units to inspect with (the app's services/unitSamplingService is the same
 * one). It is written out again here because the server scores reports too,
 * and has a different table of its own for choosing units.
 */
const SAMPLE_SIZES: [number, number, number][] = [
  [1, 1, 1], [2, 2, 1], [3, 3, 2], [4, 4, 3], [5, 5, 4], [6, 6, 5], [7, 7, 6], [8, 8, 7], [9, 9, 8],
  [10, 10, 9], [11, 12, 9], [13, 14, 10], [15, 16, 11], [17, 18, 12], [19, 21, 13], [22, 24, 14],
  [25, 27, 15], [28, 30, 16], [31, 35, 17], [36, 39, 18], [40, 45, 19], [46, 51, 20], [52, 59, 21],
  [60, 67, 22], [68, 78, 23], [79, 92, 24], [93, 110, 25], [111, 120, 26], [121, 166, 27],
  [167, 214, 28], [215, 295, 29], [296, 455, 30], [456, 920, 31],
];

/**
 * A property's sample size: what a deficiency's points are divided by, and
 * what a report prints as "Sample Size". None for a property with no units.
 */
export function sampleSize(totalUnits: unknown): number {
  const units = Math.floor(Number(totalUnits)) || 0;
  if (units < 1) return 0;
  for (const [from, to, sample] of SAMPLE_SIZES) {
    if (units >= from && units <= to) return sample;
  }
  return 32;
}

// --- the points ----------------------------------------------------------------

/**
 * PTS for a deficiency that was recorded without its own, by where it was
 * found and how severe it is. They are the values the inspection screens score
 * with (lib/outsideScoringCalculations, insideScoringCalculations and
 * unitScoringCalculations); where those hold more than one for a severity,
 * this is the one most deficiencies get.
 */
export const BASE_POINTS: Record<ScoreArea, Record<ScoreSeverity, number>> = {
  outside: { 'Life-Threatening': 24.8, Severe: 12.2, Moderate: 4.5, Low: 2.0 },
  inside: { 'Life-Threatening': 27.25, Severe: 13.4, Moderate: 5.0, Low: 2.2 },
  unit: { 'Life-Threatening': 30, Severe: 14.8, Moderate: 5.5, Low: 2.4 },
};

/** A smoke or carbon monoxide alarm fails an inspection outright; it takes no points off. */
const NO_POINTS = ['carbon monoxide', 'co alarm', 'smoke alarm', 'smoke detector'];

const round2 = (value: number): number => Math.round((value + Number.EPSILON) * 100) / 100;

const asNumber = (value: unknown): number | null => {
  if (value === null || value === undefined || value === '') return null;
  const number = typeof value === 'number' ? value : Number(String(value).trim());
  return Number.isFinite(number) ? number : null;
};

/** The points a formula starts with, as the deficiency data writes one: "14.8/n", "27.25/50xn", "0.000". */
export function formulaPoints(formula: unknown): number | null {
  if (typeof formula === 'number') return Number.isFinite(formula) ? formula : null;
  const match = String(formula ?? '').trim().match(/^(\d+(?:\.\d+)?)/);
  return match ? Number(match[1]) : null;
}

export interface DeficiencyScore {
  /** The area it counts against; null when the finding names none. */
  area: ScoreArea | null;
  /** PTS: the deficiency's points, before the sample size. */
  pts: number;
  /** Pts Lost: what it takes off the property's score. */
  ptsLost: number;
  /** Possible Score: the most its area can score; null with no area. */
  possibleScore: number | null;
}

/**
 * The points of one deficiency.
 *
 * PTS is what was recorded with it -- the points themselves, or the formula
 * they come from -- and, for one recorded with neither, BASE_POINTS. Pts Lost
 * is PTS over the sample size. It is worked out here every time rather than
 * read back, so one deficiency reads the same on every screen and in every
 * report, however long ago and on whichever device it was recorded.
 */
export function deficiencyScore(finding: Loose | null | undefined, sampleSize: unknown): DeficiencyScore {
  const row: Loose = finding || {};
  const inner: Loose = row.deficiency && typeof row.deficiency === 'object' ? row.deficiency : {};
  const area = findingArea(row);
  const severity = findingSeverity(row);
  const samples = Math.max(1, Math.floor(Number(sampleSize)) || 1);

  const formula = row.pointsFormula ?? inner.pointsFormula;
  let pts =
    asNumber(row.pts) ??
    asNumber(row.ptsLostRaw) ??
    asNumber(row.pointsLostRaw) ??
    asNumber(inner.ptsLostRaw) ??
    asNumber(inner.pointsLostRaw) ??
    formulaPoints(formula) ??
    formulaPoints(inner.pointsLostFormula);

  if (pts === null) {
    const named = [row.item, row.itemName, row.title, row.deficiencyName, row.name, inner.name, inner.selected]
      .map((value) => String(value ?? '').toLowerCase())
      .join(' ');
    const scoresNothing = area !== 'outside' && NO_POINTS.some((word) => named.includes(word));
    pts = scoresNothing ? 0 : BASE_POINTS[area ?? 'inside'][severity];
  }

  // A call-for-aid formula is written "X/50xn": fifty times the sample size.
  const divisor = /\/\s*50\s*x\s*n/i.test(String(formula ?? '')) ? 50 * samples : samples;

  // A report row that has been through here carries both numbers already, and
  // keeps them: by then it has lost the formula they were worked out from.
  const kept = asNumber(row.pts) !== null ? asNumber(row.ptsLost) : null;

  return {
    area,
    pts: round2(pts),
    ptsLost: round2(kept ?? pts / divisor),
    possibleScore: area ? POSSIBLE_SCORE[area] : null,
  };
}

export interface ReportScores {
  /** Always 100: what the three areas can score together. */
  preliminary: number;
  /** The points lost, added up. */
  calculated: number;
  /** What is left of 100, never below 0. */
  final: number;
  /** The points lost in each area. */
  lost: Record<ScoreArea, number>;
}

/** The scores of a report, from the points its deficiencies lost. */
export function reportScores(rows: { ptsLost?: number | null; area?: unknown }[]): ReportScores {
  const lost: Record<ScoreArea, number> = { outside: 0, inside: 0, unit: 0 };
  let calculated = 0;
  for (const row of rows || []) {
    const points = asNumber(row?.ptsLost) ?? 0;
    calculated += points;
    const area = scoreArea(row?.area);
    if (area) lost[area] += points;
  }
  calculated = round2(calculated);
  return {
    preliminary: PRELIMINARY_SCORE,
    calculated,
    final: round2(Math.max(0, PRELIMINARY_SCORE - calculated)),
    lost: { outside: round2(lost.outside), inside: round2(lost.inside), unit: round2(lost.unit) },
  };
}

/** A score or points as a report prints them: two decimals. */
export function formatPoints(value: unknown): string {
  return round2(asNumber(value) ?? 0).toFixed(2);
}

// --- repair time and date ------------------------------------------------------

const REPAIR_BY_SEVERITY: Record<ScoreSeverity, string> = {
  'Life-Threatening': '24 Hours',
  Severe: '24 Hours',
  Moderate: '30 Days',
  Low: '60 Days',
};

/**
 * The time a deficiency has to be repaired in: "24 Hours", "30 Days",
 * "60 Days". The deficiency data spells it many ways ("24Hrs", "24 Hrs.",
 * "30 Day"); a deficiency that carries none gets its severity's.
 */
export function repairTime(value: unknown, severity: unknown): string {
  const text = String(value ?? '').trim();
  const match = text.match(/^(\d+)\s*(h|d)/i);
  if (match) return `${match[1]} ${match[2].toLowerCase() === 'h' ? 'Hours' : 'Days'}`;
  if (/^n\/?a$/i.test(text)) return 'N/A';
  return REPAIR_BY_SEVERITY[scoreSeverity(severity)];
}

/** The repair time of a finding, wherever it keeps one. */
export function findingRepairTime(finding: Loose | null | undefined): string {
  const row: Loose = finding || {};
  const inner: Loose = row.deficiency && typeof row.deficiency === 'object' ? row.deficiency : {};
  return repairTime(row.repairTime ?? row.repairBy ?? row.repairTimeline ?? inner.repairBy, findingSeverity(row));
}

const pad2 = (value: number): string => String(value).padStart(2, '0');

/**
 * A moment as a report prints it, "11/14/2026 03:05 PM", in the time zone of
 * whatever is printing. '' for no moment. Put together by hand: the same on
 * every device, whatever its language settings.
 */
export function formatDateTime(value: unknown): string {
  if (value === null || value === undefined || value === '') return '';
  const date = value instanceof Date ? value : new Date(value as string | number);
  if (Number.isNaN(date.getTime())) return '';
  const hours = date.getHours();
  return (
    `${pad2(date.getMonth() + 1)}/${pad2(date.getDate())}/${date.getFullYear()} ` +
    `${pad2(hours % 12 || 12)}:${pad2(date.getMinutes())} ${hours < 12 ? 'AM' : 'PM'}`
  );
}

/** When a finding was recorded, wherever it keeps that; '' when it does not. */
export function findingRecordedAt(finding: Loose | null | undefined): string {
  const row: Loose = finding || {};
  return formatDateTime(row.recordedAt ?? row.timestamp ?? row.analyzedAt ?? row.capturedAt ?? row.createdAt);
}

/** What a report row adds to a finding for the points, repair time and date columns. */
export interface RowRules {
  pts: number;
  ptsLost: number;
  possibleScore: number | null;
  repairTime: string;
  recordedAt: string;
}

export function rowRules(finding: Loose | null | undefined, sampleSize: unknown): RowRules {
  const score = deficiencyScore(finding, sampleSize);
  const row: Loose = finding || {};
  // A row that has been through here keeps the moment it was given.
  const recordedAt = typeof row.recordedAt === 'string' && /\d\/\d/.test(row.recordedAt)
    ? row.recordedAt
    : findingRecordedAt(row);
  return {
    pts: score.pts,
    ptsLost: score.ptsLost,
    possibleScore: score.possibleScore,
    repairTime: findingRepairTime(row),
    recordedAt,
  };
}

// --- buildings and counts ------------------------------------------------------

/** How many buildings and units a property has, and how many were inspected. */
export interface InspectionCounts {
  buildings: number;
  units: number;
  sampleSize: number;
  unitsInspected: number;
}

const sameName = (a: string, b: string): boolean => a.trim().toLowerCase() === b.trim().toLowerCase();

/**
 * The names of a property's buildings, in order: the ones it gives them, and
 * B1, B2, ... for any it does not name.
 */
export function propertyBuildings(property: Loose | null | undefined): string[] {
  const details: Loose[] = Array.isArray(property?.buildingDetails) ? property.buildingDetails : [];
  const count = Math.max(Math.floor(Number(property?.buildings)) || 0, details.length);
  const names: string[] = [];
  for (let index = 0; index < count; index++) {
    const given = String(details[index]?.buildingId ?? details[index]?.name ?? '').trim();
    names.push(given || `B${index + 1}`);
  }
  return names;
}

/**
 * The building a report files a row under. A row recorded against "B3" reads
 * as the property's own name for its third building; a building the property
 * does not know keeps the name the row gives it.
 */
export function reportBuilding(value: unknown, names: string[]): string {
  const text = String(value ?? '').trim();
  if (!text || text === '-') return names.length === 1 ? names[0] : 'Unassigned';
  const known = names.find((name) => sameName(name, text));
  if (known) return known;
  const numbered = text.match(/^b(?:uilding)?[\s-]*(\d+)$/i);
  if (numbered) {
    const name = names[Number(numbered[1]) - 1];
    if (name) return name;
  }
  return text;
}

/**
 * Every building a report has a block for: the property's own, in their
 * order, then any other a row names. A report covers all of a property's
 * buildings, the ones with nothing found included.
 */
export function reportBuildings(names: string[] | null | undefined, rows: { building?: unknown }[]): string[] {
  const all = [...(names || [])];
  for (const row of rows || []) {
    const building = reportBuilding(row?.building, names || []);
    if (!all.some((name) => sameName(name, building))) all.push(building);
  }
  return all;
}
