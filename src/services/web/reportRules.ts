/**
 * What an inspection report says and how it is scored.
 *
 * A property starts at 100: 25 for the outside, 25 for the inside and 50 for
 * its units. A deficiency carries points (PTS) for how severe it is and where
 * it was found, and loses the property those points divided by its sample
 * size. What is left is the final score:
 *
 *   Preliminary = 25 + 25 + 50 = 100
 *   Calculated  = every deficiency's points lost, added up
 *   Final       = 100 - Calculated, never below 0
 *
 * These rules, and the words a report is printed with, are written here once.
 * The summary pages and the report read them from this file. The app and the
 * server hold copies of it -- Nspire-app/src/services/web/reportRules.ts,
 * word for word, and inspire-backend/utils/reportRules.js, the same in plain
 * JavaScript -- so a number on a screen is the number in the PDF.
 *
 * No imports: the copies run where nothing else of this repository exists.
 */

export type ScoreArea = 'outside' | 'inside' | 'unit';
export type ScoreSeverity = 'Life-Threatening' | 'Severe' | 'Moderate' | 'Low';

/** A finding or a report row, in whichever shape the web, the app or the server holds it. */
type Loose = Record<string, any>;

